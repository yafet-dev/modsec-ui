export function getLogStats(logs: LogEntry[]) {
  const blockedToday = logs.filter((l) => l.action === "blocked").length;
  const warningToday = logs.filter((l) => l.action === "warning").length;
  
  const ruleCounts = logs.reduce((acc, log) => {
    if (log.ruleId !== "-") {
      acc[log.ruleName] = (acc[log.ruleName] || 0) + 1;
    }
    return acc;
  }, {} as Record<string, number>);
  
  const topRule = Object.entries(ruleCounts).sort((a, b) => b[1] - a[1])[0];
  
  return {
    blockedToday,
    warningToday,
    topRule: topRule ? topRule[0] : "None",
  };
}

